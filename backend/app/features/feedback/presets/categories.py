def get_preset_categories(industry: str | None) -> list[dict[str, Any]]:
    """
    Return the default list of feedback categories for a given industry.
    Falls back to 'General' if industry is None or unrecognized.
    """
    if not industry:
        return INDUSTRY_CATEGORY_PRESETS["General"]

    normalized = industry.strip()
    if normalized in INDUSTRY_CATEGORY_PRESETS:
        return INDUSTRY_CATEGORY_PRESETS[normalized]

    lowered = normalized.lower()
    for key, categories in INDUSTRY_CATEGORY_PRESETS.items():
        if key.lower() == lowered or key.lower() in lowered or lowered in key.lower():
            return categories

    return INDUSTRY_CATEGORY_PRESETS["General"]
